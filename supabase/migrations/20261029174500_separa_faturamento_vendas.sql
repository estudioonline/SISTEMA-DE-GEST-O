-- Separa o faturamento financeiro do fluxo comercial de vendas.
-- Vendas aprovadas passam a aguardar o Financeiro para definir parcelas e vencimentos.

create table if not exists public.faturas_vendas (
  id uuid primary key default gen_random_uuid(),
  numero bigint generated by default as identity unique,
  venda_id uuid not null references public.vendas(id) on delete restrict,
  status text not null default 'ativa' check (status in ('ativa','cancelada')),
  forma_pagamento text not null,
  parcelas smallint not null check (parcelas between 1 and 48),
  valor_total numeric(14,2) not null check (valor_total >= 0),
  criada_em timestamptz not null default now(),
  criada_por uuid null,
  cancelada_em timestamptz null,
  cancelada_por uuid null,
  motivo_cancelamento text null
);

create unique index if not exists faturas_vendas_uma_ativa_por_venda
on public.faturas_vendas(venda_id) where status='ativa';
create index if not exists faturas_vendas_venda_idx on public.faturas_vendas(venda_id);

alter table public.faturas_vendas enable row level security;

drop policy if exists faturas_vendas_read on public.faturas_vendas;
create policy faturas_vendas_read on public.faturas_vendas
for select to authenticated using (
  private.usuario_pode('financeiro','visualizar')
  or private.usuario_pode('vendas','visualizar')
  or private.usuario_pode('relatorios','visualizar')
);
drop policy if exists faturas_vendas_insert on public.faturas_vendas;
create policy faturas_vendas_insert on public.faturas_vendas
for insert to authenticated with check (private.usuario_pode('financeiro','editar'));
drop policy if exists faturas_vendas_update on public.faturas_vendas;
create policy faturas_vendas_update on public.faturas_vendas
for update to authenticated
using (private.usuario_pode('financeiro','editar'))
with check (private.usuario_pode('financeiro','editar'));

revoke all on public.faturas_vendas from anon;
grant select,insert,update on public.faturas_vendas to authenticated;

alter table public.titulos_financeiros
  add column if not exists fatura_venda_id uuid null references public.faturas_vendas(id) on delete restrict;
create index if not exists titulos_financeiros_fatura_venda_idx
  on public.titulos_financeiros(fatura_venda_id);

-- Permite somente às rotinas controladas de faturamento manter vínculos integrados.
create or replace function private.proteger_titulo_integrado()
returns trigger language plpgsql security definer set search_path=''
as $$
declare
  v_ledger numeric;
  v_internal boolean := current_setting('app.finance_invoice_sync',true)='true';
begin
 if tg_op='DELETE' then
   if old.valor_pago>0 or exists(select 1 from public.pagamentos_titulos where titulo_id=old.id) then
     raise exception 'Título possui pagamento e não pode ser excluído';
   end if;
   if not v_internal and pg_trigger_depth()=1 and (old.venda_id is not null or old.compra_id is not null) then
     raise exception 'Título vinculado: cancele ou altere o documento de origem';
   end if;
   return old;
 end if;

 if new.valor<0 or new.valor_pago<0 or new.valor_pago>new.valor
 or (new.venda_id is not null and new.compra_id is not null) then
   raise exception 'Valores ou vínculos do título inválidos';
 end if;

 if tg_op='INSERT' then
   if not v_internal and pg_trigger_depth()=1 and (new.venda_id is not null or new.compra_id is not null) then
     raise exception 'Títulos vinculados devem ser gerados pelo documento de origem';
   end if;
 else
   if old.valor_pago>0 and new.status='cancelado' then
     raise exception 'Título com pagamento não pode ser cancelado';
   end if;
   if not v_internal and pg_trigger_depth()=1
      and (old.venda_id is not null or old.compra_id is not null)
      and (
        new.venda_id is distinct from old.venda_id
        or new.compra_id is distinct from old.compra_id
        or new.tipo is distinct from old.tipo
        or new.valor is distinct from old.valor
        or new.parcela_numero is distinct from old.parcela_numero
        or new.forma_pagamento is distinct from old.forma_pagamento
        or new.status='cancelado'
      ) then
     raise exception 'Altere o documento de origem para manter os vínculos financeiros';
   end if;
 end if;

 select coalesce(sum(pg.valor),0)
        - coalesce((
          select sum(e.valor)
          from public.estornos_pagamentos e
          join public.pagamentos_titulos original on original.id=e.pagamento_id
          where original.titulo_id=new.id
        ),0)
 into v_ledger
 from public.pagamentos_titulos pg
 where pg.titulo_id=new.id;

 if new.valor_pago is distinct from v_ledger then
   raise exception 'Saldo pago deve corresponder ao histórico de pagamentos';
 end if;

 if new.status<>'cancelado' and new.status is distinct from
    (case when v_ledger>=new.valor and new.valor>0 then 'pago'
          when v_ledger>0 then 'parcial' else 'aberto' end) then
   raise exception 'Status do título não corresponde ao saldo pago';
 end if;
 return new;
end;
$$;

-- Venda aprovada não cria títulos. Financeiro passa a ser a origem do faturamento.
create or replace function private.sincronizar_titulos_venda()
returns trigger language plpgsql security definer set search_path=''
as $$
begin
  if tg_op='UPDATE' and old.status='cancelado' and new.status<>'cancelado' then
    raise exception 'Venda cancelada não pode ser reativada';
  end if;

  if new.status='cancelado' then
    if exists(
      select 1 from public.titulos_financeiros
      where venda_id=new.id and valor_pago>0 and status<>'cancelado'
    ) then
      raise exception 'Venda possui recebimento. Estorne os pagamentos antes de cancelar.';
    end if;

    perform set_config('app.finance_invoice_sync','true',true);
    update public.titulos_financeiros
       set status='cancelado'
     where venda_id=new.id and status<>'pago';

    update public.faturas_vendas
       set status='cancelada',
           cancelada_em=coalesce(cancelada_em,now()),
           cancelada_por=coalesce(cancelada_por,auth.uid()),
           motivo_cancelamento=coalesce(motivo_cancelamento,'Venda cancelada')
     where venda_id=new.id and status='ativa';
    perform set_config('app.finance_invoice_sync','false',true);
    return new;
  end if;

  if tg_op='UPDATE'
     and exists(select 1 from public.faturas_vendas where venda_id=new.id and status='ativa')
     and (
       old.total is distinct from new.total
       or old.forma_pagamento is distinct from new.forma_pagamento
       or old.parcelas is distinct from new.parcelas
       or old.cliente_id is distinct from new.cliente_id
     ) then
    raise exception 'Venda já faturada. Cancele a fatura no Financeiro antes de alterar cobrança, cliente ou total.';
  end if;

  return new;
end;
$$;

-- Migra títulos antigos para histórico de faturas, uma única vez.
select set_config('app.finance_invoice_sync','true',true);
insert into public.faturas_vendas(
  venda_id,status,forma_pagamento,parcelas,valor_total,criada_em,criada_por,
  cancelada_em,motivo_cancelamento
)
select
  v.id,
  case when bool_and(t.status='cancelado') then 'cancelada' else 'ativa' end,
  coalesce(v.forma_pagamento,'pix'),
  greatest(1,count(*)::smallint),
  coalesce(sum(t.valor),v.total),
  coalesce(min(t.created_at),v.created_at),
  null,
  case when bool_and(t.status='cancelado') then now() else null end,
  case when bool_and(t.status='cancelado') then 'Histórico migrado de títulos cancelados' else null end
from public.vendas v
join public.titulos_financeiros t on t.venda_id=v.id and t.tipo='receber'
where not exists (select 1 from public.faturas_vendas f where f.venda_id=v.id)
group by v.id,v.forma_pagamento,v.total,v.created_at;

update public.titulos_financeiros t
set fatura_venda_id=f.id
from public.faturas_vendas f
where t.venda_id=f.venda_id and t.fatura_venda_id is null;
select set_config('app.finance_invoice_sync','false',true);

create or replace function public.criar_fatura_venda(
  p_venda_id uuid,
  p_forma_pagamento text,
  p_parcelas jsonb
)
returns jsonb language plpgsql security invoker set search_path=''
as $$
declare
  v public.vendas%rowtype;
  f public.faturas_vendas%rowtype;
  item jsonb;
  v_total numeric := 0;
  v_count integer := 0;
  v_valor numeric;
  v_vencimento date;
  v_cliente text;
begin
  if auth.uid() is null or not private.usuario_pode('financeiro','editar') then
    raise exception 'Sem permissão para faturar vendas';
  end if;

  select * into v from public.vendas where id=p_venda_id;
  if not found then raise exception 'Venda não encontrada'; end if;
  if v.status not in ('pedido','faturado') then
    raise exception 'Somente vendas aprovadas podem ser faturadas';
  end if;
  if exists(select 1 from public.faturas_vendas where venda_id=v.id and status='ativa') then
    raise exception 'Esta venda já possui fatura ativa';
  end if;
  if jsonb_typeof(p_parcelas)<>'array' or jsonb_array_length(p_parcelas)=0 then
    raise exception 'Informe ao menos uma parcela';
  end if;

  for item in select value from jsonb_array_elements(p_parcelas) loop
    v_count:=v_count+1;
    v_valor:=coalesce((item->>'valor')::numeric,0);
    v_vencimento:=nullif(item->>'vencimento','')::date;
    if v_valor<=0 or v_vencimento is null then
      raise exception 'Parcela % inválida',v_count;
    end if;
    v_total:=v_total+v_valor;
  end loop;

  if abs(v_total-v.total)>0.01 then
    raise exception 'A soma das parcelas (%) deve ser igual ao total da venda (%)',v_total,v.total;
  end if;

  insert into public.faturas_vendas(venda_id,status,forma_pagamento,parcelas,valor_total,criada_por)
  values(v.id,'ativa',coalesce(nullif(btrim(p_forma_pagamento),''),v.forma_pagamento),v_count,v.total,auth.uid())
  returning * into f;

  select nome into v_cliente from public.clientes where id=v.cliente_id;
  perform set_config('app.finance_invoice_sync','true',true);

  v_count:=0;
  for item in select value from jsonb_array_elements(p_parcelas) loop
    v_count:=v_count+1;
    v_valor:=(item->>'valor')::numeric;
    v_vencimento:=(item->>'vencimento')::date;
    insert into public.titulos_financeiros(
      tipo,descricao,entidade_nome,vencimento,valor,valor_pago,status,categoria,
      centro_custo,venda_id,fatura_venda_id,parcela_numero,forma_pagamento
    ) values (
      'receber',
      'Fatura venda '||lpad(v.fatura_numero::text,7,'0')||' - Parcela '||
        v_count||'/'||jsonb_array_length(p_parcelas),
      coalesce(v_cliente,'Consumidor'),
      v_vencimento,v_valor,0,'aberto','Vendas','Comercial',v.id,f.id,v_count,f.forma_pagamento
    );
  end loop;

  perform set_config('app.finance_invoice_sync','false',true);
  return jsonb_build_object(
    'fatura_id',f.id,'numero',f.numero,'venda_id',v.id,'parcelas',f.parcelas,
    'valor_total',f.valor_total,'status',f.status
  );
end;
$$;

create or replace function public.cancelar_fatura_venda(
  p_fatura_id uuid,
  p_motivo text
)
returns jsonb language plpgsql security invoker set search_path=''
as $$
declare f public.faturas_vendas%rowtype;
begin
  if auth.uid() is null or not private.usuario_pode('financeiro','editar') then
    raise exception 'Sem permissão para cancelar fatura';
  end if;

  select * into f from public.faturas_vendas where id=p_fatura_id;
  if not found then raise exception 'Fatura não encontrada'; end if;
  if f.status='cancelada' then return jsonb_build_object('status','cancelada'); end if;
  if exists(select 1 from public.titulos_financeiros where fatura_venda_id=f.id and valor_pago>0) then
    raise exception 'Fatura possui recebimentos. Estorne os pagamentos antes de cancelar.';
  end if;

  perform set_config('app.finance_invoice_sync','true',true);
  update public.titulos_financeiros
     set status='cancelado'
   where fatura_venda_id=f.id and status<>'pago';
  perform set_config('app.finance_invoice_sync','false',true);

  update public.faturas_vendas
     set status='cancelada',cancelada_em=now(),cancelada_por=auth.uid(),
         motivo_cancelamento=nullif(btrim(coalesce(p_motivo,'')),'')
   where id=f.id;

  return jsonb_build_object('status','cancelada','fatura_id',f.id,'venda_id',f.venda_id);
end;
$$;

revoke all on function public.criar_fatura_venda(uuid,text,jsonb) from public,anon;
revoke all on function public.cancelar_fatura_venda(uuid,text) from public,anon;
grant execute on function public.criar_fatura_venda(uuid,text,jsonb) to authenticated;
grant execute on function public.cancelar_fatura_venda(uuid,text) to authenticated;
