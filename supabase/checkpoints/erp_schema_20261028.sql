 v_id:=nullif(p_payload->>'p_venda_id','')::uuid;
 if v_id is null then
   v:=public.criar_venda_completa(nullif(p_payload->>'p_cliente_id','')::uuid,nullif(p_payload->>'p_vendedor_cadastro_id','')::uuid,
