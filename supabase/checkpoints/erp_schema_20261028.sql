    coalesce(sum(
      case when t.status not in ('pago','cancelado')
        then greatest(t.valor-t.valor_pago,0) else 0 end
    ),0),
    coalesce(sum(
      case when t.status not in ('pago','cancelado')
                 and t.vencimento < current_date
