CREATE OR REPLACE FUNCTION private.situacao_credito_cliente_impl(p_cliente_id uuid, p_excluir_venda_id uuid DEFAULT NULL::uuid)
 RETURNS TABLE(limite_credito numeric, em_aberto numeric, vencido numeric)
